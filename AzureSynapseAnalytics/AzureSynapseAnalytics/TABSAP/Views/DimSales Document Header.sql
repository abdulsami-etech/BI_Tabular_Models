  [ADLSTimestamp], 
  [PartitionColumn], 
  [Sales Document], 
  [Sales Document Type], 
  [Sales Document Category], 
  [Billing Type], 
--  [Age Tier], 
--  [Order Stages], 
--  [Stage Bucket], 
  [PatientType], 
--  [SoldTo], 
  [CCADate], 
--  [TreatmentCategory], 
  [ClinID], 
--  [Professional Category], 
--  [Advantage Program Name], 
--  [MAF], 
  [Sales Org], 
  [Division], 
  [Compliance Indicator], 
  [PO Number], 
  [IDSOrderID], 
  [Distribution Channel], 
--  [Sales Group], 
  [Sales Office], 
  [Controlling Area], 
  [Purchasing Org], 
  [Unit of Dimension for length/Width/Height], 
--  [Bill-to party], 
  [Payer], 
--  [Country of ship-to party], 
  [Customer Group1], 
  [Customer Group2], 
  [Customer Group3], 
  [Customer Group4], 
  [Customer Group5], 
