  [Sales Organization], 
  [Division], 
  [Compliance Indicator], 
  [Distribution Channel], 
--  [Sales Group], 
  [Controlling Area], 
--  [Bill-to party], 
  [PAYER], 
  [Customer Group 1], 
  [Customer Group 2], 
  [Customer Group 3], 
  [Customer Group 4], 
  [Customer Group 5], 
  [Equipment Serial Num], 
  [Initiator Company ID], 
  Year(
    Cast([Document Date] AS date)
  ), 
  [Treatment ID]