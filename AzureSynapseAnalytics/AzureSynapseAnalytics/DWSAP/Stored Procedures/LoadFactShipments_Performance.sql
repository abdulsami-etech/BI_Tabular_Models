      FROM 
        [SRCSAPFILE].[VOLUMECONFIG] 
      WHERE 
        NAME = 'CASE'
    ) 
    AND [AGE TIER] <= 19 
    AND [AGE TIER] >= 0 THEN 'ALIGNERS_SHIPPED_TEENAGERS' WHEN [ITEM CATEGORY] IN(
      SELECT 
        ITEMCATEGORY 
      FROM 
        DWSAP.VALUECONFIG 
      WHERE 
        ID IN(1, 2, 3, 4, 5)
    ) 
    AND [DELIVERABLE CATEGORY] IN(
      SELECT 
        DELIVERABLECATEGORY 
      FROM 
        DWSAP.VALUECONFIG 
      WHERE 
        ID IN(1, 2)
    ) 
    AND [PRODUCT HIERARCHY] IN (
      SELECT 
        OPERAND1 
      FROM 
        [SRCSAPFILE].[VOLUMECONFIG] 
      WHERE 
        NAME = 'CASE'
    ) 
