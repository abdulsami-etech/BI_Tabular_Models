CREATE PROC [DWSAP].[LoadFactShipments_Performance] @BATCHID [INT],@LASTSUCCESSFULLDWTIMESTAMP [DATETIME2](0) AS 
--BI-12996 New procedure
BEGIN 
IF OBJECT_ID('TEMPDB.[TABSAP].[#FACTSHIPMENTS_MATERIALIZED_TEMP]','U') IS NOT NULL 
  DROP TABLE [TABSAP].[#FACTSHIPMENTS_MATERIALIZED_TEMP] 

IF OBJECT_ID('[DWSAP].[TEMPRAWDELIVERYDATA]','U') IS NOT NULL 
  DROP TABLE [DWSAP].[TEMPRAWDELIVERYDATA] 

IF OBJECT_ID('TEMPDB..#TEMP_MULTIPLEDELIVERIESDATA','U') IS NOT NULL 
  DROP TABLE [#TEMP_MULTIPLEDELIVERIESDATA]
  
IF OBJECT_ID('[DWSAP].[LIKP]', 'U') IS NOT NULL 
  DROP TABLE [DWSAP].[LIKP] 

IF OBJECT_ID('[DWSAP].[LIPS]', 'U') IS NOT NULL 
DROP TABLE [DWSAP].[LIPS] 

IF OBJECT_ID('[DWSAP].[VBAP]', 'U') IS NOT NULL 
  DROP TABLE [DWSAP].[VBAP] 

IF OBJECT_ID('[DWSAP].[VBAK]', 'U') IS NOT NULL 
  DROP TABLE [DWSAP].[VBAK] 

DECLARE @ROWSINSERTED INT = 0, 
  @ROWSUPDATED INT = 0, 
  @ISFULLLOAD BIT = 0 DECLARE @LASTDATE DATETIME IF (
    EXISTS (
      SELECT 
        * 
      FROM 
        INFORMATION_SCHEMA.TABLES 
      WHERE 
        TABLE_SCHEMA = 'DWSAP' 
        AND TABLE_NAME = 'FactShipments_Materialized_Performance'
    )
  ) BEGIN 
SET 
  @LASTDATE = (
    SELECT 
      ISNULL (
        MAX(
          CONVERT (
            DATETIME, [DWSAP].[FactShipments_Materialized_Performance].ADLSTIMESTAMP
          )
        ), 
        '1900-01-01 00:00:00'
      ) 
    FROM 
      [DWSAP].[FactShipments_Materialized_Performance]
  ) END ELSE BEGIN 
SET 
  @LASTDATE = '1900-01-01' END CREATE TABLE [DWSAP].[LIKP] WITH (
    CLUSTERED COLUMNSTORE INDEX, 
    DISTRIBUTION = HASH([VBELN])
  ) AS 
SELECT 
  ADLSTIMESTAMP, 
  WADAT_IST, 
  [VOLEH], 
  Convert(BigInt, [VBELN]) [VBELN], 
  [NTGEW], 
  [VKORG], 
  [BTGEW], 
  KUNAG 
FROM 
  [SRCSAP].[LIKP] WITH(NOLOCK) 
WHERE 
  [WADAT_IST] <> '00000000' 
  AND LIKP.ADLSTIMESTAMP > @LASTDATE 

  --Create Index On [DWSAP].[LIKP] table
  CREATE NONCLUSTERED INDEX [LIKP_VBELN] ON [DWSAP].[LIKP]([VBELN]) 
  
  CREATE TABLE [DWSAP].[LIPS] WITH (CLUSTERED COLUMNSTORE INDEX, 
    DISTRIBUTION = HASH([VGBEL])
  ) AS 
SELECT 
  Convert(BigInt, LIPS.[POSNR]) [POSNR], 
  LIPS.[SPART], 
  LIPS.[PRODH], 
  LIPS.[PRCTR], 
  LIPS.[WERKS], 
  LIPS.[KOKRS], 
  LIPS.[MATNR], 
  LIPS.[KONTO], 
  ISNULL(LIPS.[LFIMG], 0) [LFIMG], 
  Convert(BigInt, LIPS.[VGBEL]) [VGBEL], 
  Convert(BigInt, LIPS.[VGPOS]) [VGPOS], 
  Convert(BigInt, LIPS.[VBELN]) [VBELN] 
FROM 
  [SRCSAP].[LIPS] LIPS With(NOLOCK) 
  JOIN [DWSAP].[LIKP] LIKP With(NOLOCK) ON Convert(BigInt, LIPS.[VBELN])= LIKP.[VBELN] 
  
  --Create Indexes On [DWSAP].[LIPS] table
  CREATE NONCLUSTERED INDEX [LIPS_VBELN] ON [DWSAP].[LIPS]([VBELN]) 
  CREATE NONCLUSTERED INDEX [LIPS_VGBEL] ON [DWSAP].[LIPS]([VGBEL]) 
  CREATE NONCLUSTERED INDEX [LIPS_VGPOS] ON [DWSAP].[LIPS]([VGPOS]) 
  
  CREATE TABLE [DWSAP].[VBAP] WITH (CLUSTERED COLUMNSTORE INDEX, 
    DISTRIBUTION = HASH([VBELN])
  ) AS 
SELECT 
  VBAP.[PSTYV], 
  VBAP.[ZZDELI_TYPE], 
  VBAP.[ZZTOT_QTY], 
  VBAP.[ZZTOTAL_QTY], 
  VBAP.[ZZCOMP_IND], 
  VBAP.[KWMENG], 
  VBAP.[ZZFRE_QTY], 
  VBAP.[MVGR1], 
  VBAP.[MVGR2], 
  VBAP.[MVGR3], 
  VBAP.[MVGR4], 
  VBAP.[MVGR5], 
  VBAP.[MEINS], 
  VBAP.[VRKME], 
  VBAP.[GEWEI], 
  VBAP.[ZZPROMO], 
  VBAP.[ZZTREV_DATE], 
  VBAP.[AUDAT], 
  VBAP.[LGORT], 
  VBAP.[ZZTREAT_OPT], 
  VBAP.[PRODH], 
  VBAP.[NETPR], 
  Convert(BigInt, VBAP.[VBELN]) [VBELN], 
  Convert(BigInt, VBAP.[POSNR]) [POSNR] 
FROM 
  [SRCSAP].[VBAP] VBAP WITH(NOLOCK) 
  JOIN [DWSAP].[LIPS] LIPS WITH(NOLOCK) ON Convert(BigInt, VBAP.[VBELN])=LIPS.[VGBEL] 
  AND Convert(BigInt, VBAP.[POSNR])= LIPS.[VGPOS] 

  --Create Indexes On [DWSAP].[VBAP] table
  CREATE NONCLUSTERED INDEX [VBAP_VBELN] ON [DWSAP].[VBAP]([VBELN]) 
  CREATE NONCLUSTERED INDEX [VBAP_POSNR] ON [DWSAP].[VBAP]([POSNR]) 
  
  CREATE TABLE [DWSAP].[VBAK] WITH (CLUSTERED COLUMNSTORE INDEX, 
    DISTRIBUTION = HASH([VBELN])
  ) AS 
SELECT 
  DISTINCT VBAK.[ZZDELI_CATE], 
  VBAK.[ZZSR_NO], 
  VBAK.[ZZ_IN_COM_ID], 
  VBAK.[VTWEG], 
  VBAK.[AUART], 
  VBAK.[KVGR1], 
  Convert(BigInt, VBAK.[VBELN]) [VBELN] 
FROM 
  [SRCSAP].[VBAK] VBAK WITH(NOLOCK) 
  JOIN [DWSAP].[VBAP] VBAP WITH(NOLOCK) ON Convert(BigInt, VBAK.[VBELN])= VBAP.[VBELN] 
  
  --Create Index On [DWSAP].[VBAK] table
  CREATE NONCLUSTERED INDEX [VBAK_VBELN] ON [DWSAP].[VBAK]([VBELN]) 

  CREATE TABLE [DWSAP].[TEMPRAWDELIVERYDATA] WITH (CLUSTERED COLUMNSTORE INDEX, 
    DISTRIBUTION = HASH([SALES ORDER KEY])
  ) AS 
SELECT 
  LIKP.ADLSTIMESTAMP, 
  CONCAT (
    YEAR (LIKP.WADAT_IST), 
    '-', 
    MONTH(LIKP.WADAT_IST)
  ) AS [PARTITIONCOLUMN], 
  LIKP.[VOLEH] AS [VOLUME UNIT], 
  LIKP.[VBELN] AS [DELIVERY], 
  VBAP.[PSTYV] AS [ITEM CATEGORY], 
  TVKO.[BUKRS] AS [COMPANY CODE], 
  LIKP.[NTGEW] AS [NET WEIGHT], 
  LIKP.BTGEW AS [TOTAL WEIGHT], 
  LIPS.POSNR [DELIVERYITEM], 
  LIKP.KUNAG AS [SOLD-TO PARTY], 
  LIKP.[VKORG] AS [SALES ORGANIZATION], 
  CONCAT(LIPS.[SPART], ',E') AS DIVISION_KEY, 
  LIKP.[WADAT_IST] AS [SHIPMENT DATE], 
  LIPS.[PRODH] AS [PRODUCT HIERARCHY], 
  LIPS.[PRCTR] AS [PROFIT CENTER], 
  LIPS.[WERKS] AS [PLANT], 
  CONCAT(LIPS.[PRCTR], ',', LIPS.KOKRS) AS PROFIT_CENTER_KEY, 
  LIPS.[MATNR] AS [MATERIAL NUMBER], 
  LIPS.[LFIMG] AS [DELIVERED QUANTITY], 
  --Jira Number BI-11966--Removing Initial Zeros from Sales Order Number
  REPLACE(
    LTRIM(
      REPLACE(LIPS.VGBEL, '0', ' ')
    ), 
    ' ', 
    '0'
  ) AS [SALES ORDER NUMBER], 
  REPLACE(
    LTRIM(
      REPLACE(LIPS.VGPOS, '0', ' ')
    ), 
    ' ', 
    '0'
  ) AS [SALES ORDER ITEM NUMBER], 
  VBAP.[ZZDELI_TYPE] [DELIVERABLE TYPE], 
  --Jira Number BI-11966--Removing Initial Zeros from Sales Order Number and Sales Order Item. After that those are concatenated.
  CONCAT(
    REPLACE(
      LTRIM(
        REPLACE(LIPS.VGBEL, '0', ' ')
      ), 
      ' ', 
      '0'
    ), 
    '/', 
    REPLACE(
      LTRIM(
        REPLACE(LIPS.VGPOS, '0', ' ')
      ), 
      ' ', 
      '0'
    )
  ) AS [SALES ORDER KEY], 
  ISNULL(VBAP.[ZZTOT_QTY], 0) [DELIVERABLE QUANTITY], 
  ISNULL(VBAP.[ZZTOTAL_QTY], 0) [TOTAL QUANTITY], 
  VBAK.[ZZDELI_CATE] [DELIVERABLE CATEGORY], 
  VBAK.[ZZSR_NO] AS [EQUIPMENT SERIAL NUM], 
  VBAK.[ZZ_IN_COM_ID] AS [INITIATOR COMPANY ID], 
  DOA.AGETIERCODE AS [AGE TIER], 
  VBAK.[AUART] AS [DOCUMENT TYPE], 
  CASE WHEN LIPS.PRODH LIKE 'A1A1%' THEN 'CLEAR ALIGNER' WHEN LIPS.PRODH LIKE 'A1S1%' THEN 'ITERO' ELSE NULL END AS [BUSINESS SEGMENT], 
  VBAP.[ZZCOMP_IND] [COMPLIANCE INDICATOR], 
  CASE WHEN (
    ISNULL(VBAP.[KWMENG], 0)-ISNULL(LIPS.[LFIMG], 0)
  )<= 0 THEN ISNULL(VBAP.[KWMENG], 0) ELSE (
    ISNULL(VBAP.[KWMENG], 0)-ISNULL(LIPS.[LFIMG], 0)
  ) END [TOTALORDERQUANTITY], 
  LIPS.[KONTO] AS [COST ELEMENT], 
  ISNULL(VBAP.[KWMENG], 0) [ORDER QUANTITY], 
  ISNULL(VBAP.[KWMENG], 0) [ORDER QUANTITY UNDIVIDED], 
  ISNULL(VBAP.[ZZFRE_QTY], 0) [FOC QUANTITY], 
  CASE WHEN VBAK.[VTWEG] = '20' THEN 21 WHEN VBAK.[VTWEG] = '10' 
  AND VBAK.[KVGR1] = '01' THEN 11 WHEN VBAK.[VTWEG] = '10' 
  AND VBAK.[KVGR1] = '02' THEN 12 WHEN VBAK.[VTWEG] = '10' 
  AND VBAK.[KVGR1] = '03' THEN 13 WHEN LIPS.[PRODH] LIKE 'A1S1%' 
  AND VBAP.[MVGR5] = 'Z3' THEN 11 WHEN LIPS.[PRODH] LIKE 'A1S1%' 
  AND VBAP.[MVGR5] = 'Z2' THEN 12 WHEN LIPS.[PRODH] LIKE 'A1S1%' THEN 12 WHEN LIPS.[PRODH] = 'A1A1T1C10301' THEN 11 ELSE 12 END [REPORTING CHANNEL], 
  DOA.TREATMENTLOCATION, 
  DOA.TREATINGDOCTOR, 
  VBAP.[MVGR1] AS [Material Group 1], 
  VBAP.[MVGR2] AS [Material Group 2], 
  VBAP.[MVGR3] AS [Material Group 3], 
  VBAP.[MVGR4] AS [Material Group 4], 
  VBAP.[MVGR5] AS [Material Group 5], 
  VBAP.[MEINS] AS [Base Unit of Measure], 
  VBAP.[VRKME] AS [Sales Unit], 
  VBAP.[GEWEI] AS [Weight Unit], 
  VBAP.[ZZPROMO] AS [Promotion Bucket], 
  VBAP.[ZZTREV_DATE] AS [Revenue Recognition], 
  VBAP.[AUDAT] AS [Document Date], 
  VBAP.[LGORT] AS [Storage Location], 
  VBAP.[ZZTREAT_OPT] AS [Treatment Option], 
  CASE WHEN VBAK.[ZZDELI_CATE] = 'Primary' THEN 'Paid' WHEN VBAK.[ZZDELI_CATE] = 'Secondary' 
  AND VBAP.ZZDELI_TYPE IN (
    SELECT 
      OPERAND1 
    FROM 
      [SrcSAPFile].[VolumeConfig] 
    WHERE 
      [NAME] IN (
        'DELV_TYPE_FOC', 'DELV_TYPE_DELV_QTY'
      )
  ) 
  and VBAP.[ZZFRE_QTY] = 0 THEN 'Paid' WHEN VBAK.[ZZDELI_CATE] = 'Secondary' 
  AND VBAP.ZZDELI_TYPE IN (
    SELECT 
      OPERAND1 
    FROM 
      [SrcSAPFile].[VolumeConfig] 
    WHERE 
      [NAME] IN (
        'DELV_TYPE_FOC', 'DELV_TYPE_DELV_QTY'
      )
  ) 
  and VBAP.[ZZFRE_QTY] = VBAP.[ZZTOT_QTY] THEN 'Free' WHEN VBAK.[ZZDELI_CATE] = 'Secondary' 
  AND VBAP.ZZDELI_TYPE IN (
    SELECT 
      OPERAND1 
    FROM 
      [SrcSAPFile].[VolumeConfig] 
    WHERE 
      [NAME] IN (
        'DELV_TYPE_FOC', 'DELV_TYPE_DELV_QTY'
      )
  ) 
  and (
    VBAP.[ZZTOT_QTY]-VBAP.[ZZFRE_QTY]
  ) > 0 THEN 'Paid' WHEN VBAK.[ZZDELI_CATE] = 'Secondary' 
  AND VBAP.ZZDELI_TYPE IN (
    SELECT 
      OPERAND1 
    FROM 
      [SrcSAPFile].[VolumeConfig] 
    WHERE 
      [NAME] IN (
        'DELV_TYPE_FOC', 'DELV_TYPE_DELV_QTY'
      )
  ) 
  and (
    VBAP.[ZZTOT_QTY]-VBAP.[ZZFRE_QTY]
  ) < 0 THEN 'Error' WHEN VBAK.[ZZDELI_CATE] = 'Secondary' 
  AND VBAP.ZZDELI_TYPE NOT IN (
    SELECT 
      OPERAND1 
    FROM 
      [SrcSAPFile].[VolumeConfig] 
    WHERE 
      [NAME] IN (
        'DELV_TYPE_FOC', 'DELV_TYPE_DELV_QTY'
      )
  ) 
  AND VBAP.[PRODH] LIKE 'A1A1%' 
  AND VBAP.[NETPR] = '0.00' THEN 'Free' WHEN VBAK.[ZZDELI_CATE] = 'Secondary' 
  AND VBAP.ZZDELI_TYPE NOT IN (
    SELECT 
      OPERAND1 
    FROM 
      [SrcSAPFile].[VolumeConfig] 
    WHERE 
      [NAME] IN (
        'DELV_TYPE_FOC', 'DELV_TYPE_DELV_QTY'
      )
  ) 
  AND VBAP.[PRODH] LIKE 'A1A1%' 
  AND VBAP.[NETPR] <> '0.00' THEN 'Paid' WHEN VBAK.[ZZDELI_CATE] = '' 
  AND VBAP.[PRODH] LIKE 'A1S1U1%' THEN 'Paid' WHEN VBAK.[ZZDELI_CATE] = '' 
  AND VBAP.[PRODH] LIKE 'A1S1U2%' 
  AND VBAP.[NETPR] = '0.00' THEN 'Free' WHEN VBAK.[ZZDELI_CATE] = '' 
  AND VBAP.[PRODH] LIKE 'A1S1U2%' 
  AND VBAP.[NETPR] <> '0.00' THEN 'Paid' end [Free_Paid] 
FROM 
  [DWSAP].[LIKP] LIKP 
  INNER JOIN [DWSAP].[LIPS] LIPS ON LIPS.[VBELN] = LIKP.[VBELN] 
  INNER JOIN [SRCSAP].[TVKO] TVKO ON TVKO.[BUKRS] = LIKP.[VKORG] 
  LEFT JOIN [DWSAP].[VBAP] VBAP ON VBAP.[VBELN] = LIPS.[VGBEL] 
  AND VBAP.[POSNR] = LIPS.[VGPOS] 
  LEFT JOIN [DWSAP].[VBAK] VBAK ON VBAK.[VBELN] = VBAP.[VBELN] 
  LEFT JOIN [TABSAP].[DIMORDERATTRIBUTES] DOA ON DOA.ORDERNUMBER = LIPS.VGBEL 
  CREATE NONCLUSTERED INDEX [TEMPDELIVERYSALESORDERKEY] ON [DWSAP].[TEMPRAWDELIVERYDATA] ([SALES ORDER KEY] ASC) WITH (DROP_EXISTING = OFF) 
  CREATE NONCLUSTERED INDEX [TEMPDELIVERYAGE] ON [DWSAP].[TEMPRAWDELIVERYDATA] ([AGE TIER] ASC) WITH (DROP_EXISTING = OFF) -- We calculate the data that has multiple deliveries we will then update the data on the basis oh those sales order keys
SELECT 
  [DELIVEREDQUANTITY], 
  AB.[SALES ORDER KEY], 
  [ORDER QUANTITY] INTO #TEMP_MULTIPLEDELIVERIESDATA 
FROM 
  (
    SELECT 
      SUM ([DELIVERED QUANTITY]) AS [DELIVEREDQUANTITY], 
      FSM.[SALES ORDER KEY] 
    FROM 
      [DWSAP].[TEMPRAWDELIVERYDATA] FSM 
    WHERE 
      FSM.[SALES ORDER KEY] IN (
        SELECT 
          [SALES ORDER KEY] 
        FROM 
          [TABSAP].[MULTIPLESALESORDERDELIVERIES]
      ) 
    GROUP BY 
      FSM.[SALES ORDER KEY]
  ) AC 
  INNER JOIN (
    SELECT 
      DISTINCT [ORDER QUANTITY], 
      [SALES ORDER KEY] 
    FROM 
      [DWSAP].[TEMPRAWDELIVERYDATA] FSM 
    WHERE 
      FSM.[SALES ORDER KEY] IN (
        SELECT 
          [SALES ORDER KEY] 
        FROM 
          [TABSAP].[MULTIPLESALESORDERDELIVERIES]
      )
  ) AB ON AC.[SALES ORDER KEY] = AB.[SALES ORDER KEY] 
WHERE 
  DELIVEREDQUANTITY = [ORDER QUANTITY] -- Once we have calculated the data we are going to update the values = DEliverable Quantity where it is equal to Order Quantity
UPDATE 
  [DWSAP].[TEMPRAWDELIVERYDATA] 
SET 
  [DWSAP].[TEMPRAWDELIVERYDATA].[ORDER QUANTITY] = [DWSAP].[TEMPRAWDELIVERYDATA].[DELIVERED QUANTITY] 
WHERE 
  [DWSAP].[TEMPRAWDELIVERYDATA].[SALES ORDER KEY] IN (
    SELECT 
      [SALES ORDER KEY] 
    FROM 
      #TEMP_MULTIPLEDELIVERIESDATA
      ) -- We are now updating  the data where the Order Quantity and Delivered Quantity are not equal to each other
  CREATE TABLE [TABSAP].[#FACTSHIPMENTS_MATERIALIZED_TEMP]  WITH ( CLUSTERED COLUMNSTORE INDEX, DISTRIBUTION = HASH([SALES ORDER KEY]) ) AS 
  
  /* Deriving Aligners Shipped from BASE DATA*/
SELECT 
  ADLSTIMESTAMP, 
  PARTITIONCOLUMN, 
  [DELIVERY], 
  [DELIVERYITEM], 
  [DELIVERABLE TYPE], 
  10 [VALUE TYPE], 
  [PLANT], 
  [VOLUME UNIT], 
  [ITEM CATEGORY], 
  [COMPANY CODE], 
  [SALES ORGANIZATION], 
  DIVISION_KEY, 
  CONVERT(
    VARCHAR(15), 
    [SHIPMENT DATE], 
    112
  ) [SHIPMENT DATE], 
  [PRODUCT HIERARCHY], 
  PROFIT_CENTER_KEY, 
  [DELIVERED QUANTITY], 
  [SALES ORDER NUMBER], 
  [SALES ORDER ITEM NUMBER], 
  [SALES ORDER KEY], 
  [DELIVERABLE QUANTITY], 
  [TOTAL QUANTITY], 
  [DELIVERABLE CATEGORY], 
  [BUSINESS SEGMENT], 
  CASE WHEN ISNULL([ORDER QUANTITY], 0)-ISNULL([DELIVERED QUANTITY], 0) <= 0 THEN [ORDER QUANTITY] ELSE [ORDER QUANTITY]-[TOTALORDERQUANTITY] END [TOTALORDERQUANTITY], 
  CASE WHEN [ITEM CATEGORY] NOT IN (
    SELECT 
      ITEMCATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN (1, 2, 3, 4, 5)
  ) 
  AND [DELIVERABLE CATEGORY] NOT IN (
    SELECT 
      DELIVERABLECATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN (1, 2)
  ) THEN 'ALIGNERS SHIPPED UNKNOWN' ELSE 'ALIGNERS SHIPPED' END [VOLUME SEGMENT], 
  CASE WHEN [ITEM CATEGORY] NOT IN (
    SELECT 
      ITEMCATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN(1, 2, 3, 4, 5)
  ) 
  AND [DELIVERABLE CATEGORY] NOT IN (
    SELECT 
      DELIVERABLECATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN(1, 2)
  ) THEN 'ALIGNERS SHIPPED UNKNOWN' ELSE 'ALIGNERS SHIPPED' END [VOLUME SUB-SEGMENT], 
  CASE WHEN [ITEM CATEGORY] IN (
    SELECT 
      ITEMCATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN(1, 2, 3, 4, 5)
  ) 
  AND [DELIVERABLE CATEGORY] IN (
    SELECT 
      DELIVERABLECATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN(1, 2)
  ) 
  AND [PRODUCT HIERARCHY] IN (
    SELECT 
      OPERAND1 
    FROM 
      [SRCSAPFILE].[VOLUMECONFIG] 
    WHERE 
      NAME = 'CASE'
  ) 
  AND [AGE TIER] <= 19 
  AND [AGE TIER] >= 0 THEN 'ALIGNERS_SHIPPED_TEENAGERS' WHEN [ITEM CATEGORY] IN(
    SELECT 
      ITEMCATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN(1, 2, 3, 4, 5)
  ) 
  AND [DELIVERABLE CATEGORY] IN(
    SELECT 
      DELIVERABLECATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN(1, 2)
  ) 
  AND [PRODUCT HIERARCHY] IN (
    SELECT 
      OPERAND1 
    FROM 
      [SRCSAPFILE].[VOLUMECONFIG] 
    WHERE 
      NAME = 'CASE'
  ) 
  AND (
    [AGE TIER] >= 20 
    AND [AGE TIER] <= 110 
    OR [AGE TIER] = -1
  ) THEN 'ALIGNERS_SHIPPED_ADULTS' WHEN [ITEM CATEGORY] IN (
    SELECT 
      ITEMCATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN(1, 2, 3, 4, 5)
  ) 
  AND [DELIVERABLE CATEGORY] IN (
    SELECT 
      DELIVERABLECATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN(1, 2)
  ) 
  AND [PRODUCT HIERARCHY] IN (
    SELECT 
      OPERAND1 
    FROM 
      [SRCSAPFILE].[VOLUMECONFIG] 
    WHERE 
      NAME = 'CASE'
  ) 
  AND [AGE TIER] IS NULL THEN 'ALIGNERS_SHIPPED_AGE UNKNOWN' WHEN [PRODUCT HIERARCHY] IN(
    SELECT 
      OPERAND1 
    FROM 
      [SRCSAPFILE].[VOLUMECONFIG] 
    WHERE 
      NAME = 'NONCASE'
  ) THEN 'ALIGNERS_SHIPPED_MISCELLANEOUS' 
  /* FOR ISSUE #80*/
  ELSE 'ALIGNERS_SHIPPED_UNKNOWN' END [VOLUME ACCOUNT], 
  CASE WHEN [ITEM CATEGORY] IN (
    SELECT 
      ITEMCATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN(1, 2, 3, 4, 5)
  ) 
  AND [DELIVERABLE CATEGORY] IN (
    SELECT 
      DELIVERABLECATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN(1, 2)
  ) THEN [DELIVERABLE QUANTITY] ELSE 0 END [VOLUME QUANTITY], 
  CASE WHEN [ITEM CATEGORY] IN (
    SELECT 
      ITEMCATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN(1, 2, 3, 4, 5)
  ) 
  AND [DELIVERABLE CATEGORY] IN (
    SELECT 
      DELIVERABLECATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN(1, 2)
  ) THEN [DELIVERABLE QUANTITY] ELSE 0 END [VOLUME QUANTITY UNDIVIDED], 
  1 [VOLUME COUNT], 
  [ORDER QUANTITY], 
  [ORDER QUANTITY UNDIVIDED], 
  1 [ORDER COUNT], 
  0 [FOC QUANTITY], 
  CASE WHEN [ITEM CATEGORY] =(
    SELECT 
      ITEMCATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID = 1
  ) 
  AND [DELIVERABLE CATEGORY] IN (
    SELECT 
      DELIVERABLECATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID = 1
  ) THEN 'CA-PRIMARY' WHEN [ITEM CATEGORY] IN(
    SELECT 
      ITEMCATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN(1, 2, 3, 4, 5)
  ) 
  AND [DELIVERABLE CATEGORY] IN (
    SELECT 
      DELIVERABLECATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID = 2
  ) THEN 'CA-SECONDARY' WHEN [ITEM CATEGORY] NOT IN(
    SELECT 
      ITEMCATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN(1, 2, 3, 4, 5)
  ) 
  AND [DELIVERABLE CATEGORY] NOT IN (
    SELECT 
      DELIVERABLECATEGORY 
    FROM 
      DWSAP.VALUECONFIG 
    WHERE 
      ID IN(1, 2)
  ) THEN 'CA-Others' ELSE 'Unknown' END [SEGMENT], 
  CONCAT(
    1000, 
    ',', 
    CASE WHEN [ITEM CATEGORY] IN (
